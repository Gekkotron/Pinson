/** An `<svg>` element for icon `name` (decorative: aria-hidden). */
export function icon(name, { size = 24, cls = '' } = {}) {
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', ('icon ' + cls).trim());
  const path = document.createElementNS(NS, 'path');
  path.setAttribute('d', PATHS[name] || PATHS.music);
  svg.append(path);
  return svg;
}

/** Swaps the path of an icon made by `icon()` (play ⇄ pause, heart ⇄ heartFill). */
export function setIcon(svg, name) {
  const path = svg && svg.querySelector('path');
  if (path) path.setAttribute('d', PATHS[name] || PATHS.music);
}
